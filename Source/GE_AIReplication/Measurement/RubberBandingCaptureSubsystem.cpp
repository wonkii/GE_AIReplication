#if DO_ENABLE_NET_TEST
	FAutoConsoleCommandWithWorldAndArgs SetIncoming(TEXT("RubberBanding.Incoming"),
		TEXT("Set receive emulation for this client: <min ms> <max ms> <loss percent>."),
		FConsoleCommandWithWorldAndArgsDelegate::CreateLambda([](const TArray<FString>& Args, UWorld* World)
		{
			UNetDriver* NetDriver = World && World->GetNetMode() == NM_Client ? World->GetNetDriver() : nullptr;
			int32 MinMs, MaxMs, Loss;
			if (!NetDriver || Args.Num() != 3 || !LexTryParseString(MinMs, *Args[0]) || !LexTryParseString(MaxMs, *Args[1]) ||
				!LexTryParseString(Loss, *Args[2]) || MinMs < 0 || MaxMs < MinMs || Loss < 0 || Loss > 100)
			{
				UE_LOG(LogRubberBandingCapture, Warning, TEXT("Run in a connected client: RubberBanding.Incoming <min ms> <max ms> <loss 0-100>"));
				return;
			}
			if (IsRubberBandingSweepActive(World) || URubberBandingCaptureSubsystem::GetActive(World))
			{
				UE_LOG(LogRubberBandingCapture, Warning, TEXT("Stop the current capture before changing incoming emulation."));
				return;
			}
			FPacketSimulationSettings Settings = NetDriver->PacketSimulationSettings;
			Settings.PktIncomingLagMin = MinMs;
			Settings.PktIncomingLagMax = MaxMs;
			Settings.PktIncomingLoss = Loss;
			NetDriver->SetPacketSimulationSettings(Settings);
			UE_LOG(LogRubberBandingCapture, Display, TEXT("%s incoming %d-%d ms, %d%% loss"), *World->GetName(), MinMs, MaxMs, Loss);
		}));
#endif
#endif
